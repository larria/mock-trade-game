const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
function buildPWA(directory = root, output = null) {
    const version = JSON.parse(fs.readFileSync(path.join(directory, 'package.json'), 'utf8')).version;
    if (!/^\d+\.\d+\.\d+$/.test(version)) throw new Error('Invalid package version');
    const changelog = fs.readFileSync(path.join(directory, 'CHANGELOG.md'), 'utf8');
    const section = changelog.split(/^## /m).slice(1).find(entry => entry.startsWith(`v${version} · `));
    const notes = section?.split(/\r?\n/).filter(line => line.startsWith('- ')).map(line => line.slice(2).trim());
    if (!notes?.length || notes.length > 12 || notes.some(note => !note || note.length > 240)) {
        throw new Error(`Add 1–12 release notes for v${version} to CHANGELOG.md`);
    }
    const assets = ['index.html', 'styles.css', 'vendor/echarts.min.js', 'stock-universe.js', 'decoder.js', 'engine.js', 'market-chart.js', 'game.js', 'pwa.js', 'manifest.webmanifest', 'icons/icon.svg', 'icons/icon-192.png', 'icons/icon-512.png', 'icons/icon-maskable-512.png', 'icons/apple-touch-icon.png'];
    const template = fs.readFileSync(path.join(directory, 'scripts/sw-template.js'), 'utf8');
    const integrity = contents => `sha256-${crypto.createHash('sha256').update(contents).digest('base64')}`;
    const assetHashes = Object.fromEntries(assets.map(file => [file, integrity(fs.readFileSync(path.join(directory, file)))]));
    const build = crypto.createHash('sha256').update(JSON.stringify({ version, notes, assetHashes })).update(template).digest('hex').slice(0, 16);
    const release = { version, build, notes };
    const generate = (file, contents) => fs.writeFileSync(path.join(directory, file), contents);
    const versionScript = `/* Generated by npm run build:pwa. */\nwindow.APP_RELEASE = Object.freeze(${JSON.stringify(release)});\n`;
    const precache = { 'version.js': integrity(versionScript), ...assetHashes };
    const files = Object.keys(precache);
    generate('version.js', versionScript);
    generate('version.json', `${JSON.stringify(release, null, 2)}\n`);
    generate('sw.js', `/* Generated by npm run build:pwa. */\nconst RELEASE = ${JSON.stringify(release)};\nconst ASSETS = ${JSON.stringify(precache)};\n${template}`);
    if (output) {
        fs.rmSync(output, { recursive: true, force: true });
        fs.mkdirSync(output, { recursive: true });
        for (const file of [...files, 'version.json', 'sw.js', 'vendor/LICENSE-ECHARTS.txt', 'vendor/NOTICE-ECHARTS.txt']) {
            const target = path.join(output, file);
            fs.mkdirSync(path.dirname(target), { recursive: true });
            fs.copyFileSync(path.join(directory, file), target);
        }
        fs.writeFileSync(path.join(output, '.nojekyll'), '');
    }
    return { release, assets: files };
}
if (require.main === module) {
    const result = buildPWA(root, process.argv.includes('--dist') ? path.join(root, 'dist') : null);
    process.stdout.write(`PWA v${result.release.version} · ${result.release.build} · ${result.assets.length} cached assets\n`);
}
module.exports = { buildPWA };

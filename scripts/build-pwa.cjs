const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
function buildPWA(directory = root, output = null) {
    const version = JSON.parse(fs.readFileSync(path.join(directory, 'package.json'), 'utf8')).version;
    if (!/^\d+\.\d+\.\d+(?:-[\w.-]+)?$/.test(version)) throw new Error('Invalid package version');
    const assets = ['index.html', 'styles.css', 'vendor/echarts.min.js', 'stock-universe.js', 'decoder.js', 'engine.js', 'market-chart.js', 'game.js', 'pwa.js', 'manifest.webmanifest', 'icons/icon.svg', 'icons/icon-192.png', 'icons/icon-512.png', 'icons/icon-maskable-512.png', 'icons/apple-touch-icon.png'];
    const template = fs.readFileSync(path.join(directory, 'scripts/sw-template.js'), 'utf8');
    const hash = crypto.createHash('sha256').update(version).update(template);
    assets.forEach(file => { hash.update(file); hash.update(fs.readFileSync(path.join(directory, file))); });
    const release = { version, build: hash.digest('hex').slice(0, 16) };
    const files = ['version.js', ...assets];
    fs.writeFileSync(path.join(directory, 'version.js'), `/* Generated by npm run build:pwa. */\nwindow.APP_RELEASE = Object.freeze(${JSON.stringify(release)});\n`);
    fs.writeFileSync(path.join(directory, 'sw.js'), `/* Generated by npm run build:pwa. */\nconst RELEASE = ${JSON.stringify(release)};\nconst ASSETS = ${JSON.stringify(files)};\n${template}`);
    if (output) {
        fs.rmSync(output, { recursive: true, force: true });
        fs.mkdirSync(output, { recursive: true });
        for (const file of [...files, 'sw.js', 'vendor/LICENSE-ECHARTS.txt', 'vendor/NOTICE-ECHARTS.txt']) {
            const target = path.join(output, file);
            fs.mkdirSync(path.dirname(target), { recursive: true });
            fs.copyFileSync(path.join(directory, file), target);
        }
        fs.writeFileSync(path.join(output, '.nojekyll'), '');
    }
    return { release, assets: files };
}
if (require.main === module) {
    const result = buildPWA(root, process.argv.includes('--dist') ? path.join(root, 'dist') : null);
    process.stdout.write(`PWA v${result.release.version} · ${result.release.build} · ${result.assets.length} cached assets\n`);
}
module.exports = { buildPWA };

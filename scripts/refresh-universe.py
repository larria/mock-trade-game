#!/usr/bin/env python3
"""Refresh all four stock pools; fail without replacing the last complete snapshot."""
import concurrent.futures
import datetime
import json
import math
import re
import time
import urllib.parse
import urllib.request
from pathlib import Path
import xlrd

ROOT = Path(__file__).resolve().parent.parent
API = 'https://vip.stock.finance.sina.com.cn/quotes_service/api/json_v2.php/'
GROUPS = [('hs300', '沪深 300'), ('csi500', '中证 500'), ('star', '科创板'), ('chinext', '创业板')]

def request(url):
    error = None
    for attempt in range(3):
        try:
            req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0', 'Referer': 'https://finance.sina.com.cn/'})
            with urllib.request.urlopen(req, timeout=20) as response:
                return response.read()
        except Exception as exc:
            error = exc
            time.sleep(.5 * (attempt + 1))
    raise RuntimeError(f'Unable to load {url}: {error}')

def constituents(index, expected):
    url = f'https://oss-ch.csindex.com.cn/static/html/csindex/public/uploads/file/autofile/cons/{index}cons.xls'
    sheet = xlrd.open_workbook(file_contents=request(url)).sheet_by_index(0)
    header = [str(value) for value in sheet.row_values(0)]
    code_idx = next(i for i, value in enumerate(header) if 'Constituent Code' in value)
    name_idx = next(i for i, value in enumerate(header) if 'Constituent Name' in value and '(Eng)' not in value)
    exchange_idx = next(i for i, value in enumerate(header) if '交易所Exchange' in value)
    items = []
    dates = set()
    for row in range(1, sheet.nrows):
        values = sheet.row_values(row)
        code = str(values[code_idx]).split('.')[0].zfill(6)
        exchange = values[exchange_idx]
        prefix = 'sh' if '上海' in exchange else 'sz' if '深圳' in exchange else None
        if not prefix or not re.fullmatch(r'\d{6}', code):
            raise ValueError(f'Unsupported constituent: {code} {exchange}')
        items.append({'code': code, 'name': str(values[name_idx]), 'fullCode': prefix + code})
        dates.add(str(values[0]))
    if len(items) != expected or len({item['fullCode'] for item in items}) != expected:
        raise ValueError(f'{index}: expected {expected} unique constituents, got {len(items)}')
    return {'items': items, 'asOf': sorted(dates)[-1], 'source': url}

def board(node, pattern):
    count_url = API + 'Market_Center.getHQNodeStockCount?' + urllib.parse.urlencode({'node': node})
    count = int(json.loads(request(count_url)))
    if count < 100:
        raise ValueError(f'{node}: implausible listing count {count}')
    def page(number):
        query = urllib.parse.urlencode({'page': number, 'num': 80, 'sort': 'symbol', 'asc': 1, 'node': node})
        rows = json.loads(request(API + 'Market_Center.getHQNodeData?' + query))
        if not isinstance(rows, list): raise ValueError('Invalid listing page')
        return rows
    with concurrent.futures.ThreadPoolExecutor(max_workers=4) as executor:
        pages = list(executor.map(page, range(1, math.ceil(count / 80) + 1)))
    items = []
    for row in (item for page_rows in pages for item in page_rows):
        code = str(row['code']); full = str(row['symbol'])
        if not re.fullmatch(pattern, full) or full[2:] != code: raise ValueError(f'{node}: unexpected board code {full}')
        items.append({'code': code, 'name': row['name'], 'fullCode': full})
    if len(items) != count or len({i['fullCode'] for i in items}) != count or int(json.loads(request(count_url))) != count:
        raise ValueError(f'{node}: incomplete/changed listing; retry refresh')
    return {'items': items, 'asOf': datetime.datetime.now(datetime.timezone(datetime.timedelta(hours=8))).strftime('%Y%m%d'), 'source': API + 'Market_Center.getHQNodeData?node=' + node}

def main():
    data = {}
    data['hs300'] = constituents('000300', 300)
    data['csi500'] = constituents('000905', 500)
    data['star'] = board('kcb', r'sh68[89]\d{3}')
    data['chinext'] = board('cyb', r'sz30\d{4}')
    stocks = {}
    markets = []
    for key, name in GROUPS:
        group = data[key]
        markets.append({'id': key, 'name': name, 'count': len(group['items']), 'asOf': group['asOf'], 'source': group['source']})
        for item in group['items']:
            stock = stocks.setdefault(item['fullCode'], {**item, 'markets': []})
            stock['markets'].append(key)
    snapshot = {'asOf': datetime.datetime.now(datetime.timezone(datetime.timedelta(hours=8))).strftime('%Y-%m-%d'), 'markets': markets, 'stocks': sorted(stocks.values(), key=lambda item: item['fullCode'])}
    payload = json.dumps(snapshot, ensure_ascii=False, separators=(',', ':'))
    source = '''/* Generated by npm run refresh:universe. Complete current market snapshot. */
(function(root) {
'use strict';
const snapshot = __PAYLOAD__;
const ids = snapshot.markets.map(m => m.id);
function pool(selected = ids) {
    const choices = new Set(selected);
    return snapshot.stocks.filter(stock => stock.markets.some(id => choices.has(id)));
}
function describe(selected = ids) {
    return snapshot.markets.filter(m => selected.includes(m.id)).map(m => m.name).join(' / ');
}
const api = { ...snapshot, pool, describe };
root.StockUniverse = api;
if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(globalThis);
'''.replace('__PAYLOAD__', payload)
    temp = ROOT / 'stock-universe.js.tmp'
    temp.write_text(source, encoding='utf-8')
    temp.replace(ROOT / 'stock-universe.js')
    print(json.dumps({'asOf': snapshot['asOf'], 'markets': [{k: m[k] for k in ['id', 'count', 'asOf']} for m in markets], 'unique': len(snapshot['stocks'])}, ensure_ascii=False))

if __name__ == '__main__': main()
